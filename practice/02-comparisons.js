
// JavaScript Comparison Operators

let x = 5;
let y = 10;

// Equality and inequality
console.log(x == y);  // Output: false
console.log(x != y);  // Output: true
console.log(x === y); // Output: false
console.log(x !== y); // Output: true

// Relational operators
console.log(x < y);  // Output: true
console.log(x > y);  // Output: false
console.log(x <= y); // Output: true
console.log(x >= y); // Output: false
