
 // JavaScript Objects - Properties and Updates

// Create an object with three properties
let person = {
    name: "Alice",
    age: 30,
    isEmployed: true
};

// Access object properties
console.log(person.name);
console.log(person["age"]);

// Update an existing property
person.age = 31;

// Add a new property
person.city = "New York";

// Display the updated object
console.log(person);
