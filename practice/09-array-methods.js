
// JavaScript Arrays - Basic Methods

let fruits = ["apple", "cherry", "banana"];

// Access an element by its index (starting at 0)
console.log(fruits[2]); // Output: banana

// Original array
console.log(fruits);

// Push: add an element to the end
fruits.push("orange");
console.log(fruits);

// Pop: remove the last element
fruits.pop();
console.log(fruits);

// Shift: remove the first element
fruits.shift();
console.log(fruits);

// Unshift: add an element to the beginning
fruits.unshift("kiwi");
console.log(fruits);
