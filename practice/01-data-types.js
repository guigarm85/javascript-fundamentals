
 // JavaScript Data Types

// String
let nameAlice = "Alice";
console.log(nameAlice); // Output: Alice

// Number
let age = 25;
let temperature = -5.6;
console.log(age); // Output: 25
console.log(temperature); // Output: -5.6

// Boolean
let isActive = true;
let isLoggedIn = false;
console.log(isActive); // Output: true
console.log(isLoggedIn); // Output: false

// Undefined
let someVar;
console.log(someVar); // Output: undefined

// Null
let result = null;
console.log(result); // Output: null

// Checking data types
console.log(typeof nameAlice); // Output: string
console.log(typeof age); // Output: number
console.log(typeof isActive); // Output: boolean
console.log(typeof someVar); // Output: undefined
console.log(typeof result); // Output: object
